export const generateTimeSeriesMetrics = (points = 30): MetricDataPoint[] => {
  const data: MetricDataPoint[] = [];
  const now = Date.now();
  for (let i = points; i >= 0; i--) {
    const time = new Date(now - i * 60 * 1000);
    const timeStr = time.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    const cpuBase = 58 + Math.sin(i / 3) * 12 + (Math.random() * 8 - 4);
    const memBase = 72 + Math.cos(i / 4) * 6 + (Math.random() * 4 - 2);
    data.push({
      timestamp: timeStr,
      cpu: Math.min(100, Math.max(15, parseFloat(cpuBase.toFixed(1)))),
      memory: Math.min(100, Math.max(20, parseFloat(memBase.toFixed(1)))),
      disk: 61.8 + (Math.random() * 0.4 - 0.2),
      networkIn: Math.round(1100 + Math.sin(i / 2) * 200 + Math.random() * 100),
      networkOut: Math.round(1950 + Math.cos(i / 2) * 300 + Math.random() * 120),
      responseTime: parseFloat((75 + Math.random() * 25).toFixed(1)),
      errorRate: parseFloat((0.2 + Math.random() * 0.4).toFixed(2)),
      rps: Math.round(4800 + Math.random() * 600),
    });
  }
  return data;
};

